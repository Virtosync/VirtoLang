"""Turn a ``.vlang`` program into a standalone executable (``vlang build``).

How it works
------------
VirtoLang runs on Python, so the executable is made by PyInstaller:

1. The program, every ``.vlang`` file next to it, and the active ``packages``
   folder are copied into a staging folder.
2. A tiny launcher script is generated.  It starts the VirtoLang interpreter on
   the staged entry file (found inside the bundle at run time).
3. PyInstaller is run on the launcher.  The staging folder is added as data and
   every Python module the program imports is added as a hidden import.
4. Any PyInstaller flag you pass to ``vlang build`` is forwarded unchanged.

This module only needs the interpreter for the optional syntax check, so it can
be imported cheaply from the command line and from the ``build_exe`` built-in.
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

import vmodules

# Folders never copied into the bundle when collecting a project's .vlang files.
_SKIPPED_DIRS = {"dist", "build", "node_modules", "__pycache__", "packages"}

# Matches "import a.b" / "from a.b import c" at the start of a statement.
_IMPORT_RE = re.compile(
    r"(?:^|[;{}])[ \t]*(?:import|from)[ \t]+([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)",
    re.MULTILINE,
)

_LAUNCHER = '''\
"""Generated by "vlang build" - starts the bundled VirtoLang program."""
import os
import sys

import vlang

_root = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
_project = os.path.join(_root, "vproject")
_packages = os.path.join(_project, "packages")
if os.path.isdir(_packages):
    os.environ["VIRTOLANG_PACKAGES"] = _packages
os.environ.pop("VIRTOLANG_VENV", None)

if __name__ == "__main__":
    raise SystemExit(vlang.main([os.path.join(_project, {entry!r})] + sys.argv[1:]))
'''


class BuildError(RuntimeError):
    """Raised when an executable cannot be built."""


def runtime_source_dir():
    """Folder holding VirtoLang's own ``.py`` files (needed by PyInstaller)."""
    if getattr(sys, "frozen", False):
        return os.path.join(getattr(sys, "_MEIPASS", vmodules.install_dir()), "vsrc")
    return os.path.dirname(os.path.abspath(__file__))


def _flag_value(flags, names):
    """Value of the first ``--name value`` / ``--name=value`` flag in ``flags``."""
    for index, flag in enumerate(flags):
        for name in names:
            if flag == name and index + 1 < len(flags):
                return flags[index + 1]
            if name.startswith("--") and flag.startswith(name + "="):
                return flag.split("=", 1)[1]
    return None


def _has_flag(flags, names):
    """True if any of ``names`` appears in ``flags`` (with or without ``=value``)."""
    return any(flag in names or flag.split("=", 1)[0] in names for flag in flags)


def _find_python():
    """Python interpreter used to run PyInstaller."""
    if not getattr(sys, "frozen", False):
        return sys.executable
    for name in ("python3", "python", "py"):
        found = shutil.which(name)
        if found:
            return found
    raise BuildError(
        "building executables needs Python on this computer to run PyInstaller "
        "(install Python from python.org, then try again)"
    )


def _ensure_pyinstaller(python):
    """Make sure PyInstaller can be imported by ``python``, installing it if not."""
    probe = [python, "-c", "import PyInstaller"]
    if subprocess.run(probe, capture_output=True).returncode == 0:
        return
    print("PyInstaller is not installed - installing it now...", file=sys.stderr)
    status = subprocess.run([python, "-m", "pip", "install", "pyinstaller"]).returncode
    if status != 0:
        raise BuildError("could not install PyInstaller (try: pip install pyinstaller)")


def _stage_project(entry, stage):
    """Copy the program's ``.vlang`` files and the packages folder into ``stage``.

    Returns the entry file's path relative to the staged project folder.
    """
    project = os.path.dirname(os.path.abspath(entry))
    target = os.path.join(stage, "vproject")
    os.makedirs(target, exist_ok=True)
    for folder, dirs, files in os.walk(project):
        dirs[:] = [
            d
            for d in dirs
            if d not in _SKIPPED_DIRS
            and not d.startswith(".")
            and not vmodules.is_venv(os.path.join(folder, d))
        ]
        for name in files:
            if name.endswith(".vlang"):
                source = os.path.join(folder, name)
                destination = os.path.join(target, os.path.relpath(source, project))
                os.makedirs(os.path.dirname(destination), exist_ok=True)
                shutil.copyfile(source, destination)

    packages = vmodules.packages_dir()
    if packages and os.path.isdir(packages):
        shutil.copytree(packages, os.path.join(target, "packages"), dirs_exist_ok=True)
    return os.path.relpath(os.path.abspath(entry), project)


def _python_imports(stage_project):
    """Names imported by the staged programs that are not VirtoLang modules.

    These are passed to PyInstaller as hidden imports, because it cannot see
    imports made from ``.vlang`` code.
    """
    found = set()
    for folder, _dirs, files in os.walk(stage_project):
        for name in files:
            if name.endswith(".vlang"):
                path = os.path.join(folder, name)
                with open(path, "r", encoding="utf-8-sig", errors="replace") as handle:
                    found.update(_IMPORT_RE.findall(handle.read()))

    def is_vlang(dotted):
        top = dotted.split(".")[0]
        for base in (stage_project, os.path.join(stage_project, "packages")):
            if os.path.isdir(os.path.join(base, top)) or os.path.isfile(
                os.path.join(base, top + ".vlang")
            ):
                return True
        return False

    return sorted(name for name in found if not is_vlang(name))


def _without_flag(flags, long_name):
    """``flags`` with ``--long_name VALUE`` / ``--long_name=VALUE`` removed."""
    result = []
    skip = False
    for flag in flags:
        if skip:
            skip = False
        elif flag == long_name:
            skip = True
        elif not flag.startswith(long_name + "="):
            result.append(flag)
    return result


def _normalize_flags(flags):
    """Accept friendly spellings such as ``--one-file`` for PyInstaller flags."""
    aliases = {"--one-file": "--onefile", "--one-dir": "--onedir",
               "--no-console": "--noconsole"}
    return [aliases.get(flag, flag) for flag in flags]


def build(entry, flags=(), output=None, keep_temp=False, check=True, onefile=False,
          extra_sources=()):
    """Build ``entry`` (a ``.vlang`` file) into an executable.

    ``flags`` is a list of extra PyInstaller command-line flags (for example
    ``["--windowed", "--icon", "app.ico"]``).  ``output`` is the folder for the
    result (default ``dist``).      ``onefile`` chooses a single-file executable or (the default) a
        folder, which starts much faster because a single file must unpack itself
        on every launch; ``flags`` may also say which.  Returns the
    path of the executable.  ``extra_sources`` are further ``.vlang`` files to
    bundle.  Raises ``BuildError`` if the build fails, and lets syntax errors
    in the program propagate when ``check`` is true.
    """
    entry = os.path.abspath(entry)
    if not entry.endswith(".vlang"):
        raise BuildError("source file must have a .vlang extension")
    if not os.path.isfile(entry):
        raise BuildError(f"file not found: {entry}")

    flags = _normalize_flags(flags)
    for extra in extra_sources:
        if not os.path.isfile(extra):
            raise BuildError(f"file not found: {extra}")
        from interpreter import Interpreter

        with open(entry, "r", encoding="utf-8-sig") as handle:
            Interpreter(handle.read(), filename=entry).check()

    python = _find_python()
    _ensure_pyinstaller(python)

    name = _flag_value(flags, ("-n", "--name")) or os.path.splitext(
        os.path.basename(entry)
    )[0]
    if output is None:
        output = _flag_value(flags, ("--distpath",)) or "dist"
    output = os.path.abspath(output)
    flags = _without_flag(flags, "--distpath")

    if _has_flag(flags, ("-D", "--onedir")):
        onefile = False
    elif _has_flag(flags, ("-F", "--onefile")):
        onefile = True
    else:
        flags.append("--onefile" if onefile else "--onedir")

    stage = tempfile.mkdtemp(prefix="vlang-build-")
    try:
        relative_entry = _stage_project(entry, stage)
        for extra in extra_sources:
            # Files outside the program's folder are bundled next to the entry file.
            destination = os.path.join(stage, "vproject", os.path.basename(extra))
            if not os.path.exists(destination):
                shutil.copyfile(extra, destination)
        launcher = os.path.join(stage, "launcher.py")
        with open(launcher, "w", encoding="utf-8") as handle:
            handle.write(_LAUNCHER.format(entry=relative_entry))

        command = [
            python,
            "-m",
            "PyInstaller",
            "--noconfirm",
            "--specpath",
            stage,
            "--paths",
            runtime_source_dir(),
            "--add-data",
            os.path.join(stage, "vproject") + os.pathsep + "vproject",
            "--distpath",
            output,
        ]
        for module in _python_imports(os.path.join(stage, "vproject")):
            command += ["--hidden-import", module]
        if not _has_flag(flags, ("-n", "--name")):
            command += ["--name", name]
        if not _has_flag(flags, ("--workpath",)):
            command += ["--workpath", os.path.join(stage, "work")]
        command += flags
        command.append(launcher)

        status = subprocess.run(command).returncode
        if status != 0:
            raise BuildError(f"PyInstaller failed (exit status {status})")
    finally:
        if keep_temp:
            print(f"Build files kept in {stage}", file=sys.stderr)
        else:
            shutil.rmtree(stage, ignore_errors=True)

    suffix = ".exe" if sys.platform == "win32" else ""
    if onefile:
        return os.path.join(output, name + suffix)
    return os.path.join(output, name, name + suffix)


def build_cli(argv):
    """Handle ``vlang build FILE [options] [PyInstaller flags]``.  Returns a status."""
    import argparse

    parser = argparse.ArgumentParser(
        prog="vlang build",
        allow_abbrev=False,
        description="Build a .vlang program into a standalone executable with "
        "PyInstaller. Any option not listed here is passed to PyInstaller "
        "(for example --windowed, --icon app.ico, --name MyApp, --onedir, "
        "--add-data SRC:DEST).",
    )
    parser.add_argument("file", help="The .vlang program to build")
    parser.add_argument(
        "-o", "--output", metavar="DIR", help="Folder for the result (default: dist)"
    )
    parser.add_argument(
        "--keep-temp", action="store_true", help="Keep the temporary build files"
    )
    parser.add_argument(
        "--no-check", action="store_true", help="Skip the syntax check before building"
    )
    args, extra = parser.parse_known_args(argv)

    try:
        exe = build(
            args.file,
            extra,
            output=args.output,
            keep_temp=args.keep_temp,
            check=not args.no_check,
        )
    except (BuildError, OSError) as exc:
        print(f"VirtoLang build error: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:
        # A syntax error in the program is reported like any other VirtoLang error.
        import vlang

        with open(args.file, "r", encoding="utf-8-sig") as handle:
            source = handle.read()
        vlang._print_language_error(exc, args.file, source)
        return 1
    print(f"Built {exe}")
    return 0
